"""
ScriptRepair — Skill 5: 自动修复

如果 QualityValidator 发现质量问题，调用 ScriptRepair 自动修复。
这是一个"第二轮"Agent，专注于缺陷修复而不是全量重生成。

输出：修复后的 script list
"""

import json
import logging
from typing import Callable

from .base_agent import BaseAgent

logger = logging.getLogger(__name__)

# ─────────────────────────────────────────────────────────────────────────────
# SCRIPT REPAIR SYSTEM PROMPT
# ─────────────────────────────────────────────────────────────────────────────

SCRIPT_REPAIR_SYSTEM = """\
You are an expert language teacher refining lesson scripts.
Your task is NOT to rewrite everything, but to FIX SPECIFIC ISSUES in an already-good script.

## Your Job

1. You will receive:
   - A lesson script (generated by another teacher)
   - A list of specific quality issues
   - The lesson plan (for context)

2. Your mission:
   - FIX ONLY the identified problems
   - PRESERVE what's already good
   - Use the same tool format as the original script
   - Maintain consistency with the rest of the script

3. Repair strategies depend on issue type:

   **Issue: Missing interaction/questions**
   → Add ask_question tools at appropriate points (max 1 per 4-5 sentences)

   **Issue: Explanations lack depth/meaning/contrast**
   → Add cultural_context, usage_and_collocation, or synonym_and_variation tools
   → Enhance existing explain_sentence text to show more layers

   **Issue: Tone is robotic/templated**
   → Rewrite speak content to be more natural and conversational
   → Add transition remarks to improve flow
   → Show more personality and genuine interest

   **Issue: Missing coverage of deep sentences**
   → Add grammar_breakdown or cultural_context tools
   → Ensure deep sentences get adequate explanation

   **Issue: Pacing/energy is monotonous**
   → Add transition remarks between dense sections
   → Add stage summaries to provide breathing room
   → Vary the types of tools used (not all explain_sentence)

4. Output format:
   - Return ONLY the FIXED/ADDED tools/instructions
   - Or return ONLY the FULL script if major restructuring is needed
   - Make it clear what changed

## Important

- Do NOT remove existing tools unless they're redundant
- Do NOT rewrite good sections just for the sake of it
- Do NOT introduce new problems while fixing old ones
- Maintain the teacher's "voice" and style
- Keep explanations accurate and authentic
"""

# ─────────────────────────────────────────────────────────────────────────────
# SCRIPT REPAIR CLASS
# ─────────────────────────────────────────────────────────────────────────────


class ScriptRepair(BaseAgent):
    """自动修复脚本缺陷的Agent"""

    def __init__(self, **kwargs):
        super().__init__(agent_name="ScriptRepair", **kwargs)

    def repair(
        self,
        script: list,
        lesson_plan: list,
        issues: list,
        suggestions: list = None,
    ) -> list:
        """
        修复脚本中的特定问题。

        Args:
            script: 原始脚本（包含缺陷）
            lesson_plan: 课程规划（用于上下文）
            issues: QualityValidator 发现的具体问题列表
            suggestions: 改进建议列表

        Returns:
            修复后的脚本（可能是完整脚本或差异指令）
        """
        if not issues:
            logger.info("[ScriptRepair] 无问题需要修复")
            return script

        logger.info(f"[ScriptRepair] 修复脚本，发现 {len(issues)} 个问题")

        # 1. 加载知识库（提供修复指导）
        knowledge_base = self.load_reference_files([
            "teaching_methodology.md",
            "pedagogical_frameworks/questioning_strategies.md",
            "pedagogical_frameworks/clt_principles.md",
        ])

        # 2. 构建修复提示词
        system_prompt = self._build_repair_prompt(knowledge_base)

        # 3. 构建修复请求
        user_prompt = self._build_repair_request(
            script,
            lesson_plan,
            issues,
            suggestions,
        )

        # 4. 调用LLM进行修复
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]

        # 这里可能需要工具调用或直接返回修复后的脚本
        # 对于简单的修复，直接要求LLM返回修复建议JSON
        repair_result = self._request_json(
            messages=messages,
            temperature=0.5,  # 中等温度，保证创意和一致性平衡
            max_tokens=4096,
            scene="script_repair",
            expected_type=dict,
        )

        # 5. 应用修复
        repaired_script = self._apply_repairs(
            script,
            repair_result,
        )

        logger.info(f"[ScriptRepair] 修复完成，脚本更新")
        return repaired_script

    def _build_repair_prompt(self, knowledge_base: dict) -> str:
        """构建系统提示词"""
        parts = [SCRIPT_REPAIR_SYSTEM]

        # 加入相关知识库内容
        parts.append("\n## Teaching Knowledge for Repair Reference\n")

        if "questioning_strategies.md" in knowledge_base:
            parts.append("### Effective Questioning (for adding questions):")
            parts.append(knowledge_base["questioning_strategies.md"][:1500])

        if "clt_principles.md" in knowledge_base:
            parts.append("\n### CLT Principles (for improving meaning-focused explanations):")
            parts.append(knowledge_base["clt_principles.md"][:1000])

        return "\n".join(parts)

    def _build_repair_request(
        self,
        script: list,
        lesson_plan: list,
        issues: list,
        suggestions: list = None,
    ) -> str:
        """构建修复请求"""
        parts = [
            "## Original Script\n",
            json.dumps(script, ensure_ascii=False, indent=2),
            "",
            "## Lesson Plan\n",
            json.dumps(lesson_plan, ensure_ascii=False, indent=2),
            "",
            "## Issues to Fix\n",
        ]

        for i, issue in enumerate(issues, 1):
            parts.append(f"{i}. {issue}")

        if suggestions:
            parts.append("\n## Suggestions for Improvement\n")
            for i, suggestion in enumerate(suggestions, 1):
                parts.append(f"{i}. {suggestion}")

        parts.append("\n## Repair Instructions\n")
        parts.append("""\
1. Identify WHERE in the script each issue occurs
2. Generate FIXED tool calls for those specific locations
3. Output JSON with structure: {
     "repairs": [
       {
         "position": "at sentence_id X / after item Y",
         "issue": "the problem",
         "fix": "the solution",
         "tools_to_add": [...],
         "tools_to_modify": [...],
         "explanation": "why this fixes the issue"
       }
     ]
   }

4. If fixes affect multiple sections, provide the full corrected script
5. Preserve what's good — only change what's broken
        """)

        return "\n".join(parts)

    @staticmethod
    def _apply_repairs(
        original_script: list,
        repair_result: dict,
    ) -> list:
        """
        应用修复建议到原始脚本。

        Args:
            original_script: 原始脚本
            repair_result: 修复建议结果

        Returns:
            修复后的脚本
        """
        # 如果 repair_result 包含完整的新脚本，直接返回
        if "full_script" in repair_result and repair_result["full_script"]:
            logger.info("[ScriptRepair] 使用完整重写脚本")
            return repair_result["full_script"]

        # 否则，应用具体的修复
        repaired_script = list(original_script)  # 复制原脚本

        repairs = repair_result.get("repairs", [])
        if not repairs:
            logger.info("[ScriptRepair] 无具体修复指令")
            return original_script

        # 这是一个简化的实现
        # 在实际应用中，需要更复杂的位置追踪和插入逻辑
        logger.info(f"[ScriptRepair] 应用 {len(repairs)} 个修复")

        # TODO: 实现精确的修复应用逻辑
        # 对于现在，返回原脚本
        # 改进版本应该：
        # 1. 追踪每个修复的位置
        # 2. 合并新工具到脚本中
        # 3. 确保顺序正确

        return repaired_script
